    ACCOUNT_REACTIVATE = "ACCOUNT_REACTIVATE"
    STAFF_ROLE_GRANT = "STAFF_ROLE_GRANT"
    STAFF_ROLE_REVOKE = "STAFF_ROLE_REVOKE"
    RECOVERY_NOTIFICATION_EVENTS = "RECOVERY_NOTIFICATION_EVENTS"
    RECOVERY_SAFETY_ENFORCEMENT = "RECOVERY_SAFETY_ENFORCEMENT"


